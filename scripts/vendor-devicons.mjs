// Vendors the Devicon marks Lumen uses into packages/ui/src/icons/vendor/.
// Downloads each SVG from the pinned Devicon release, drops the brand fills so
// the mark takes `currentColor`, writes the normalised .svg next to the
// license, and regenerates devicon-paths.ts (the path data the React
// components render inline, so no icon costs a network request).
//
// Usage (from the repository root): node scripts/vendor-devicons.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const VERSION = "2.17.0";
const BASE = `https://cdn.jsdelivr.net/npm/devicon@${VERSION}/icons`;

// Lumen key → Devicon file. "plain" (single-color) variants where Devicon ships
// one; Rust, Deno and MySQL only ship an "original" that is already a single
// shape, so the fill is dropped the same way.
const ICONS = {
  node: "nodejs/nodejs-plain",
  python: "python/python-plain",
  go: "go/go-plain",
  rust: "rust/rust-original",
  ruby: "ruby/ruby-plain",
  php: "php/php-plain",
  java: "java/java-plain",
  dotnet: "dotnetcore/dotnetcore-plain",
  deno: "denojs/denojs-original",
  bun: "bun/bun-plain",
  docker: "docker/docker-plain",
  postgres: "postgresql/postgresql-plain",
  mysql: "mysql/mysql-original",
  redis: "redis/redis-plain",
  mongodb: "mongodb/mongodb-plain",
};

const root = resolve(import.meta.dirname, "..");
const outDir = resolve(root, "packages/ui/src/icons/vendor");

const entries = [];
for (const [key, file] of Object.entries(ICONS)) {
  const response = await fetch(`${BASE}/${file}.svg`);
  if (!response.ok) {
    throw new Error(`${file}: HTTP ${String(response.status)}`);
  }
  const source = await response.text();
  const viewBox = /viewBox="([^"]+)"/.exec(source)?.[1];
  if (viewBox === undefined) {
    throw new Error(`${file}: no viewBox`);
  }
  const paths = [...source.matchAll(/<path\b([^>]*?)\/?>/g)].map((match) => {
    const attributes = match[1] ?? "";
    const d = /\bd="([^"]+)"/.exec(attributes)?.[1];
    if (d === undefined) {
      throw new Error(`${file}: path without d`);
    }
    const fillRule = /\bfill-rule="([^"]+)"/.exec(attributes)?.[1];
    return fillRule === undefined ? { d } : { d, fillRule };
  });
  if (/<(?:circle|rect|polygon|ellipse|g|use|image)\b/.test(source)) {
    throw new Error(`${file}: has shapes other than paths; normalise it by hand`);
  }
  const normalised =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="currentColor">` +
    paths
      .map(
        (path) =>
          `<path d="${path.d}"${path.fillRule === undefined ? "" : ` fill-rule="${path.fillRule}"`}/>`,
      )
      .join("") +
    "</svg>\n";
  writeFileSync(resolve(outDir, `${key}.svg`), normalised);
  entries.push({ key, file, viewBox, paths });
  console.log("vendored", key, "←", file);
}

const ts = `// Generated by scripts/vendor-devicons.mjs from Devicon ${VERSION} (MIT).
// Do not edit by hand; see vendor/LICENSES.md.

export interface VendoredIcon {
  viewBox: string;
  paths: readonly { d: string; fillRule?: "evenodd" | "nonzero" }[];
}

export const DEVICON_VERSION = "${VERSION}";

export const DEVICONS = {
${entries
  .map(
    (entry) =>
      `  /** devicon ${entry.file} */\n  ${JSON.stringify(entry.key)}: {\n    viewBox: ${JSON.stringify(entry.viewBox)},\n    paths: ${JSON.stringify(entry.paths)},\n  },`,
  )
  .join("\n")}
} as const satisfies Record<string, VendoredIcon>;

export type DeviconKey = keyof typeof DEVICONS;
`;
writeFileSync(resolve(outDir, "devicon-paths.ts"), ts);
console.log("wrote devicon-paths.ts");
